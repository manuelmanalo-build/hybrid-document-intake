@dataclass(frozen=True)
class Deliverable:
    asset_type: str
    quantity: int
    description: str
    due: date | None


@dataclass
class Brief:
    brief_id: str
    template: str  # FORM, MEMO, SLIDES, EMAIL_ONLY
    client: str
    brand: str
    campaign: str
    sow_stated: str | None
    received: date
    submitted_by: str
    submitter_email: str
    objective: str
    kpi: str | None
    kpi_target: str | None
    audience: str
    markets: str
    budget: Decimal | None
    budget_text: str
    launch: date
    end: date
    approver: str
    mandatories: str
    deliverables: list[Deliverable]
    email: str | None = None
    email_launch: date | None = None
    email_added: list[Deliverable] = field(default_factory=lambda: list[Deliverable]())
    media_plan: bool = False
    scanned: bool = False
    duplicate_of: str | None = None
    edge_case: str = ""


def _d(code: str, quantity: int, description: str, due: str | None) -> Deliverable:
    return Deliverable(code, quantity, description, D(due) if due else None)


